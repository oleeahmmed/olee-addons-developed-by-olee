def bn_digits(value):
    return str(value).translate(BN_DIGITS)


def _words(n):
    """Integer -> Bangla words with the South-Asian grouping (কোটি, লক্ষ, হাজার, শত)."""
    if n == 0:
        return 'শূন্য'
    parts = []
    for size, name in ((10 ** 7, 'কোটি'), (10 ** 5, 'লক্ষ'), (1000, 'হাজার'), (100, 'শত')):
        if n >= size:
            count = n // size
            parts.append((_words(count) if count >= 100 else _ONES[count]) + ' ' + name)
            n %= size
    if n:
        parts.append(_ONES[n])
    return ' '.join(parts)


def bn_amount_words(amount):
    amount = round(abs(amount or 0.0), 2)
    taka = int(amount)
    poisha = int(round((amount - taka) * 100))
    text = _words(taka) + ' টাকা'
    if poisha:
        text += ' ' + _words(poisha) + ' পয়সা'
    return text + ' মাত্র'
